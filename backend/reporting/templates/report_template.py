# Template registry
TEMPLATES = {
    "daily": DailyReportTemplate,
    "weekly": WeeklyReportTemplate,
    "monthly": MonthlyReportTemplate,
}


def get_template(report_type: str, config: Optional[TemplateConfig] = None) -> ReportTemplate:
    """
    Get a report template by type.
    
    Args:
        report_type: Type of report ('daily', 'weekly', 'monthly')
        config: Optional template configuration
        
    Returns:
        ReportTemplate instance
        
    Raises:
        ValueError: If report type is not recognized
    """
    template_class = TEMPLATES.get(report_type.lower())
    if template_class is None:
        raise ValueError(
            f"Unknown report type: {report_type}. "
            f"Available types: {list(TEMPLATES.keys())}"
        )
    return template_class(config)


def list_templates() -> List[str]:
    """Get list of available template types"""
    return list(TEMPLATES.keys())
